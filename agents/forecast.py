# ForecastAgent: 気象予測を行うエージェント
# 霧氷・凝華・放射霧に対応（設計書v1.4 + radiation_fog.md / 放射霧PDF v0.1 準拠）
#
# このエージェントの責務:
#   1. 地点を特定する(登録地点はそのまま / 未知地点は Maps API で座標・標高を解決)
#   2. 未知地点は地形からタグを推定し A〜E パターンに振り分け、結果をキャッシュ保存
#   3. 気象データを取得し、現象別(霧氷・凝華・放射霧)の判定ロジックで予測
#   4. 予測ログを predictions.json に保存(後日 実績と突き合わせて精度検証)
#
# 放射霧ロジックは PDF「放射霧予測 v0.1」の5パターン体制を反映:
#   A 鉄板組 / B 隠れ強豪 / C 気まぐれ / D 湖畔派 / E 谷筋派
#   どのパターンにも該当しない地点は「共通4条件のみ」の標準ロジックにフォールバック。

import os
from datetime import datetime, timezone, timedelta
from google.adk.agents import LlmAgent
from google.adk.tools import FunctionTool
from google.genai import types

from tools.weather import fetch_forecast, fetch_all_forecasts
