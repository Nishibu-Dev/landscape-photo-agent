# ---------------------------------------------------------------------------
# 霧氷のタイプ(霧のパターン A〜E とは別物)
#   霧のパターンは「冷気・水蒸気が溜まる地形か」で決めているが、霧氷のタイプは
#   「水蒸気の出どころ」と「冬の気候」で決まるため、地点ごとに別の属性として持つ。
#   登録地点: データで確かめた地点だけに確定タイプを付け、それ以外は雲中型・未確定で判定する。
#   未登録地点: LLM が推定した地形タグから estimate_rime_type で機械的に決める
#              (湿原系×盆地地形なら湿原・盆地型、それ以外は雲中型・未確定。湧水型は推定しない)。
#
#   湿原・盆地型: 盆地にたまった湿った空気(雲・霧を含む)から育つ。明け方まで湿り気が
#                保たれるかが鍵。乾いていく夜は出ない。(田ノ原湿原・踊場湿原の実績。尾瀬ヶ原・戦場ヶ原も同じ仕組みと判断)
#   湧水型      : 凍らない湧水・梓川の水蒸気が、乾いた晴れの夜に冷えた枝に凍りつく。
#                水温が一定の湧水が前提で、普通の川・湖には当てはめない。(上高地の実績)
#   雲中型・未確定: 地点が雲や霧の中に入り、過冷却の粒が枝について凍る。気温≦-1℃かつ
#                T-Td≦1.5℃(ほぼ飽和)で機械判定する。上記以外の登録地点と、湿原・盆地型と推定されなかった
#                未登録の地点はここ。
# ---------------------------------------------------------------------------
RIME_TYPE_WETLAND = "湿原・盆地型"
RIME_TYPE_SPRING = "湧水型"
RIME_TYPE_DEFAULT = "雲中型・未確定"


def get_spot_attributes(name: str) -> dict | None:
    """登録地点の地形属性を返す（エイリアス解決込み）。未登録は None。"""
    resolved = SPOT_ALIASES.get(name, name)
    return SPOT_ATTRIBUTES.get(resolved)


def get_rime_type(name: str) -> str:
    """
    登録地点の霧氷タイプを返す。確定タイプのない登録地点・未登録地点は「雲中型・未確定」。
    未登録地点を地形タグから推定するときは estimate_rime_type を使う
    (tools/weather.py の resolve_rime_type が両者を使い分ける)。
    """
    attrs = get_spot_attributes(name) or {}
    return attrs.get("rime_type", RIME_TYPE_DEFAULT)


# 湿原・盆地型と推定しないタグ。
#   乾燥湿原: 明け方まで湿り気が保たれるかが鍵の型なので、乾きやすい湿原には当てはめない
#             (登録地点の大阿原湿原も雲中型・未確定のまま)。
#   稜線上・峠: 湿った空気が溜まらず流れ落ちる地形。
_WETLAND_RIME_EXCLUDE_TAGS = ("乾燥湿原", "稜線上", "峠")


def estimate_rime_type(main_group: str | None, tags: list[str] | None) -> str:
    """
    未登録地点の霧氷タイプを、LLM が推定した地形(main_group/tags)から機械的に決める。

    - 湿原系 × 盆地地形(乾燥湿原・稜線上・峠を除く) → 湿原・盆地型
    - それ以外 → 雲中型・未確定
    - 湧水型は推定しない。「水温が一定の湧水」が前提で、地名や地形からは見分けられないため、
      データで確かめた登録地点(SPOT_ATTRIBUTES の rime_type)だけに付ける。
    """
    tags = tags or []
    if (
        main_group == "湿原系"
        and "盆地地形" in tags
        and not any(t in tags for t in _WETLAND_RIME_EXCLUDE_TAGS)
    ):
        return RIME_TYPE_WETLAND
    return RIME_TYPE_DEFAULT